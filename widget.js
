  var sr = null, wantListening = false, submitOnStop = false, committedText = "", timer = null, secs = 0;

  function setStatus(msg, isErr) {
    var s = document.getElementById("mip-st");
    s.style.display = msg ? "block" : "none";
    s.style.color = isErr ? "#be123c" : "#065f46";
    s.textContent = msg || "";
  }

