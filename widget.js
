  function localBackupExtract(rawText) {
    var txt = String(rawText || "").trim().replace(/(\d+(?:[.,]\d+)?)\s*mil\b/gi, function(_, n) {
      return String(Math.round(parseFloat(n.replace(",", ".")) * 1000));
    });
    var docType = "quote";
    if (/\b(factura|invoice|facturar|cobro)\b/i.test(txt)) docType = "invoice";
    else if (/\b(recibo|receipt|abono recibido)\b/i.test(txt)) docType = "receipt";
    else if (/\b(compraventa|bill of sale)\b/i.test(txt)) docType = "billsale";
    else if (/\b(alquiler|renta|lease)\b/i.test(txt)) docType = "lease";
    else if (/\b(contrato|contract)\b/i.test(txt)) docType = "contract";
    else if (/\b(relevo|waiver)\b/i.test(txt)) docType = "waiver";
    else if (/\b(pagar[eé]|promissory)\b/i.test(txt)) docType = "promissory";
    else if (/\b(orden de cambio|change order|adicional)\b/i.test(txt)) docType = "change";
    else if (/\b(orden de trabajo|work order)\b/i.test(txt)) docType = "workorder";
    else if (/\b(orden de compra|purchase order)\b/i.test(txt)) docType = "po";
    else if (/\b(conduce|delivery)\b/i.test(txt)) docType = "delivery";

    var issuer = "";
    var issM = txt.match(/\b(?:de parte de|emitid[oa] por)\s+([^,.]+?)(?=\s+(?:por|para|de\s+\$?\d|con|en\s+\$?\d)|$)/i);
    if (issM) issuer = issM[1].trim();

    var client = "";
    var cliM = txt.match(/\b(?:para(?:\s+que)?|cliente|a favor de)\s+([^,.]+?)(?=\s+(?:de parte de|por|de\s+\$?\d|con|en\s+\$?\d)|$)/i);
    if (cliM) client = cliM[1].trim();

    var dep = 0;
    var depM = txt.match(/(?:dep[oó]sito|pronto|adelanto|abono)\s*(?:de)?\s*\$?\s*(\d[\d,]*(?:\.\d+)?)|\$?\s*(\d[\d,]*(?:\.\d+)?)\s*de\s*(?:dep[oó]sito|pronto|adelanto|abono)/i);
    if (depM) dep = parseFloat((depM[1] || depM[2] || "0").replace(/,/g, "")) || 0;

    var taxPct = /\bcon ivu\b/i.test(txt) ? 11.5 : 0;
    var taxM = txt.match(/(\d+(?:\.\d+)?)\s*%\s*(?:de\s*)?(?:ivu|tax|impuesto)/i);
    if (taxM) taxPct = parseFloat(taxM[1]) || 0;

    var nums = [], rgx = /\$?\s*(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)/g, m;
    while ((m = rgx.exec(txt)) !== null) {
      var v = parseFloat(m[1].replace(/,/g, ""));
      if (v > 0 && v !== taxPct && v !== dep) nums.push(v);
    }
    return {
      docType: docType,
      issuer: issuer,
      client: client,
      items: [{ desc: "Servicios profesionales y suministro según alcance acordado.", qty: 1, price: nums[0] || dep || 0 }],
      taxPct: taxPct, taxAmt: 0, discAmt: 0, retPct: 0,
      dep: docType === "receipt" ? 0 : dep,
      notes: "Condiciones y alcance acordados entre las partes."
    };
  }

